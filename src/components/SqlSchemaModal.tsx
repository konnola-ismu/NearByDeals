export function SqlSchemaModal({ isOpen, onClose }: SqlSchemaModalProps) {
  const [copied, setCopied] = useState(false)

  if (!isOpen) return null

  const handleCopy = () => {
    navigator.clipboard?.writeText(SUPABASE_SQL_SCRIPT)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal-container modal-large" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div>
            <h3>⚡ Supabase Database Setup Script</h3>
            <p className="modal-subtext">
              Run this in your Supabase SQL Editor to create tables for Users, Customers, and Deals.
            </p>
          </div>
          <button className="modal-close-btn" onClick={onClose}>
            ✕
          </button>
        </div>

        <div className="sql-box-wrap">
          <div className="sql-actions-bar">
            <a
              href="https://supabase.com/dashboard/project/eaupnggxhmkadixnvxyw/sql/new"
              target="_blank"
              rel="noopener noreferrer"
              className="sql-external-link"
            >
              Open Supabase SQL Editor ↗
            </a>
            <button className="copy-btn" onClick={handleCopy}>
              {copied ? '✓ SQL Copied!' : '📋 Copy Full SQL Script'}
            </button>
          </div>
          <pre className="sql-code-block">{SUPABASE_SQL_SCRIPT}</pre>
        </div>

        <div className="modal-actions">
          <button className="primary-btn" onClick={onClose}>
            Done
          </button>
        </div>
      </div>
    </div>
  )
}
